import { test, expect, type Page } from '@playwright/test'
import { approveContact, adminSession, registerAccount, verificationCode } from './auth-helpers'
import { DatabaseSync } from 'node:sqlite'
import path from 'node:path'

test.use({ locale: 'zh-CN' })
const route = (path: string) => `${process.env.FORMA_TEST_STUDIO_PREFIX || ''}${path}`
const switchLanguage = (page: Page, language: 'en' | 'zh-CN') => page.locator('.language-switcher select').first().selectOption(language)

test('Chinese registration, projects, settings and administration retain language and user content', async ({ page, playwright }) => {
  const backend = await playwright.request.newContext({ baseURL: process.env.FORMA_TEST_BACKEND_URL })
  const email = `chinese-${Date.now()}@example.com`
  try {
    await page.goto(route('/register'))
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
    await expect(page).toHaveTitle('Forma — AI 应用工作室')
    await page.getByLabel('姓名', { exact: true }).fill('中文用户')
    await page.getByLabel('邮箱地址', { exact: true }).fill(email)
    await page.getByLabel('密码', { exact: true }).fill('password123')
    const challengeResponse = page.waitForResponse(response => response.url().endsWith('/api/auth/register') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '发送验证码', exact: true }).click()
    const challenge = await (await challengeResponse).json()
    const code = await verificationCode(challenge.challenge_id)
    await page.getByLabel('验证码', { exact: true }).fill(code)
    await switchLanguage(page, 'en')
    await expect(page.getByRole('heading', { name: 'Verify your contact' })).toBeVisible()
    await expect(page.getByLabel('Verification code', { exact: true })).toHaveValue(code)
    await switchLanguage(page, 'zh-CN')
    await page.getByRole('button', { name: '验证并提交审核' }).click()
    await expect(page.getByRole('heading', { name: '等待审核' })).toBeVisible()
    await approveContact(backend, email)
    await page.getByRole('link', { name: '返回登录' }).click()
    await page.screenshot({ path: '/tmp/forma-chinese-login.png', fullPage: true })
    await page.getByLabel('邮箱或手机号', { exact: true }).fill(email)
    await page.getByLabel('密码', { exact: true }).fill('password123')
    await page.getByRole('button', { name: '登录 Forma' }).click()
    await expect(page.getByRole('heading', { name: /中文用户/ })).toBeVisible()
    await page.getByRole('button', { name: '新建应用' }).click()
    // A name that is also a UI translation key must remain user content.
    await page.getByLabel('应用名称', { exact: true }).fill('Projects')
    const brief = '一个供团队记录日常任务和想法的简单列表应用。'
    await page.getByLabel('描述你的想法', { exact: false }).fill(brief)
    await page.locator('.source-format-options label').filter({ hasText: '单文件' }).click()
    await page.getByRole('button', { name: '开始构建', exact: true }).click()
    await expect(page.locator('.project-name')).toContainText('Projects')
    await expect(page.getByText('产品描述已就绪。请查看范围，确认后进入体验设计。', { exact: true })).toBeVisible()
    await switchLanguage(page, 'en')
    await expect(page.getByRole('button', { name: 'Approve design' })).toBeVisible()
    await expect(page.locator('.context-card')).toContainText(brief)
    await switchLanguage(page, 'zh-CN')
    await page.reload()
    await expect(page.getByRole('button', { name: '确认设计' })).toBeVisible()
    await expect(page.locator('.project-name')).toContainText('Projects')
    await page.getByRole('button', { name: '确认设计', exact: true }).click()
    await page.getByRole('button', { name: '开始构建', exact: true }).click()
    await page.getByRole('button', { name: '构建第 1 阶段', exact: true }).click()
    await expect(page.getByRole('button', { name: '确认第 1 阶段', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: '发布', exact: true }).click()
    await expect(page.getByRole('dialog')).toContainText('每次发布包含 1 小时托管。')
    await page.getByRole('button', { name: '发布应用', exact: true }).click()
    await expect(page.getByRole('heading', { name: '你的应用已上线。' })).toBeVisible()
    await expect(page.getByRole('dialog')).toContainText('版本 1 已上线，可以分享了。')
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(page.getByText(/版本 1 已上线，公开链接已可分享/)).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: '/tmp/forma-chinese-builder-mobile.png', fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(route('/settings'))
    await expect(page.getByRole('heading', { name: '界面语言' })).toBeVisible()
    await expect(page.locator('.account-card')).toContainText('普通用户')
    const adminToken = await adminSession(backend)
    await page.evaluate(token => localStorage.setItem('forma_token', token), adminToken)
    await page.goto(route('/admin'))
    await expect(page.getByRole('heading', { name: '管理中心' })).toBeVisible()
    await expect(page.getByLabel('每个用户的项目上限', { exact: false })).toHaveValue('5')
    await page.getByRole('button', { name: /用户管理/ }).click()
    const row = page.locator('.table-row').filter({ hasText: email })
    await expect(row).toContainText('正常')
    await row.getByRole('button', { name: '删除 中文用户' }).click()
    await expect(page.getByRole('dialog')).toContainText('永久删除 中文用户')
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.screenshot({ path: '/tmp/forma-chinese-admin.png', fullPage: true })
    await switchLanguage(page, 'en')
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('heading', { name: 'Administration' })).toBeVisible()
  } finally { await backend.dispose() }
})

for (const method of ['email', 'sms'] as const) {
test(`Chinese ${method} password recovery and form errors use the selected language`, async ({ page, playwright }) => {
  const backend = await playwright.request.newContext({ baseURL: process.env.FORMA_TEST_BACKEND_URL })
  const contact = method === 'email' ? `reset-cn-${Date.now()}@example.com` : `+86136${String(Date.now()).slice(-8)}`
  try {
    await registerAccount(backend, { [method === 'email' ? 'email' : 'phone']: contact, name: '密码测试', password: 'password123' })
    // Represent an existing account beyond the shared registration/reset cooldown.
    if (!process.env.FORMA_TEST_DATA_DIR) throw new Error('Missing isolated browser-test database')
    const db = new DatabaseSync(path.join(process.env.FORMA_TEST_DATA_DIR, 'control.db'))
    try { db.prepare('UPDATE auth_rate_events SET created_at=created_at-61').run() } finally { db.close() }
    await page.goto(route('/login'))
    await page.getByRole('button', { name: '登录 Forma' }).click()
    const identity = page.getByLabel('邮箱或手机号', { exact: true })
    expect(await identity.evaluate((element: HTMLInputElement) => element.validationMessage)).toBe('请填写此字段。')
    await identity.fill(contact)
    await page.getByLabel('密码', { exact: true }).fill('wrong-password')
    await page.getByRole('button', { name: '登录 Forma' }).click()
    await expect(page.getByRole('alert')).toHaveText('邮箱、手机号或密码不正确')
    await switchLanguage(page, 'en')
    await expect(page.getByRole('alert')).toHaveText('Email, mobile number, or password is incorrect')
    await switchLanguage(page, 'zh-CN')
    await page.getByRole('link', { name: '忘记密码？' }).click()
    if (method === 'sms') {
      await page.setViewportSize({ width: 390, height: 844 })
      await page.getByRole('button', { name: '手机（+86）', exact: true }).click()
    }
    await page.getByLabel(method === 'email' ? '邮箱地址' : '中国大陆手机号', { exact: true }).fill(contact)
    const resetResponse = page.waitForResponse(response => response.url().endsWith('/api/auth/password-reset') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '发送重置验证码' }).click()
    const response = await resetResponse
    expect(response.ok()).toBeTruthy()
    const challenge = await response.json()
    const code = await verificationCode(challenge.challenge_id)
    await expect(page.getByRole('heading', { name: '设置新密码' })).toBeVisible()
    await expect(page.locator('.auth-heading')).not.toContainText('{{')
    await page.getByLabel('验证码', { exact: true }).fill(code)
    await page.getByLabel('新密码', { exact: true }).fill('new-password456')
    await page.getByLabel('确认新密码', { exact: true }).fill('different-password')
    await page.getByRole('button', { name: '重置密码', exact: true }).click()
    await expect(page.getByRole('alert')).toHaveText('两次输入的密码不一致。')
    await page.getByLabel('确认新密码', { exact: true }).fill('new-password456')
    await page.screenshot({ path: `/tmp/forma-chinese-reset-${method}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.getByRole('button', { name: '重置密码', exact: true }).click()
    await expect(page.getByRole('heading', { name: '密码已更新' })).toBeVisible()
    await page.getByRole('link', { name: '返回登录' }).click()
    await page.getByLabel('邮箱或手机号', { exact: true }).fill(contact)
    await page.getByLabel('密码', { exact: true }).fill('new-password456')
    await page.getByRole('button', { name: '登录 Forma' }).click()
    await expect(page.getByRole('button', { name: '新建应用' })).toBeVisible()
  } finally { await backend.dispose() }
})
}
